function verifyProductionSVMFallback
root=fileparts(mfilename('fullpath'));source=fileread(fullfile(root,'VoiceDiseaseModeling_Final.m'));
source=strrep(source,sprintf('\r\n'),sprintf('\n'));head=sprintf('function VoiceDiseaseModeling_Final\n');assert(startsWith(source,head));
extra=[newline 'function checkFallback()' newline ...
    'rng(1405);cfg=configuration();cfg.ForceSVMFallback=true;' newline ...
    'X=[randn(80,3)-1;randn(80,3)+1];Y=[zeros(80,1);ones(80,1)];' newline ...
    'fit=false(160,1);fit([1:60,81:140])=true;cal=~fit;w=ones(160,1);' newline ...
    'm=fitModel(X,Y,w,"SVM",fit,cal,(1:160)'',cfg);' newline ...
    'assert(strcmp(m.SolverInfo.Backend,''SMO_converged_fallback''));' newline ...
    'assert(m.Core.ConvergenceInfo.Converged);p=modelProbability(m,X(cal,:));' newline ...
    'assert(numel(p)==40 && all(isfinite(p)) && all(p>=0 & p<=1));' newline ...
    'fprintf(''PRODUCTION_SVM_FALLBACK_PASSED\n'');' newline 'end' newline];
source=[head sprintf('checkFallback();return;\n') source(numel(head)+1:end) extra];
folder=fullfile(getenv('RUNNER_TEMP'),'svm-fallback-check');if ~isfolder(folder),mkdir(folder);end
fid=fopen(fullfile(folder,'VoiceDiseaseModeling_Final.m'),'w');assert(fid~=-1);fwrite(fid,source,'char');fclose(fid);
old=pwd;cleanup=onCleanup(@()cd(old)); %#ok<NASGU>
cd(folder);addpath(folder,'-begin');clear VoiceDiseaseModeling_Final;
try
    VoiceDiseaseModeling_Final;
catch err
    report=string(getReport(err,'extended','hyperlinks','off'));
    report=replace(replace(replace(report,"%","%25"),char(13),"%0D"),char(10),"%0A");
    fprintf(2,'::error title=Reference SVM fallback check::%s\n',report);rethrow(err);
end
end
